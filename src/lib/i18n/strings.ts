export function t(lang: Lang, key: string): string {
  return strings[lang]?.[key] ?? strings.en[key] ?? key;
}

export function detectLang(text: string): Lang {
  const fr = /\b(le|la|les|de|du|des|un|une|avec|dans|est|sont|par|cette|pour|qui|que|pas|douleur|céphalée|fièvre|depuis|antécédents|traitement|femme|homme|ans|nuque)\b/i;
  const it = /\b(il|lo|la|le|di|del|della|un|una|con|nel|nella|per|che|sono|questo|questa|dolore|cefalea|febbre|paziente|donna|uomo|anni|collo)\b/i;
  const frMatches = (text.match(fr) || []).length;
  const itMatches = (text.match(it) || []).length;
  if (frMatches > 3 && frMatches > itMatches) return 'fr';
  if (itMatches > 3 && itMatches > frMatches) return 'it';
  return 'en';
}
